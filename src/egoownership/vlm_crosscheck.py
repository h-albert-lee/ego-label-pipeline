def _parse_label_response(raw: str) -> dict[str, Any]:
    """Extract the label plus each per-aspect evidence field, one by one, from
    a VLM text response — mirroring scene_records.jsonl's auto_key_evidence
    field names so the two are directly comparable."""
    raw = raw.strip()
    # Strip markdown fences if present.
    raw = re.sub(r"^```(?:json)?\s*", "", raw, flags=re.MULTILINE)
    raw = re.sub(r"\s*```$", "", raw, flags=re.MULTILINE)
    try:
        data = json.loads(raw)
        label = _canonicalize_label(str(data.get("label", "")))
        if label is None:
            label = _extract_label_from_text(raw)
        result: dict[str, Any] = {"label": label}
        for field_name in _EVIDENCE_FIELDS:
            value = data.get(field_name)
            result[field_name] = str(value).strip() if value else ""
        return result
    except (json.JSONDecodeError, ValueError):
        label = _extract_label_from_text(raw)
        result = {"label": label, **{field_name: "" for field_name in _EVIDENCE_FIELDS}}
        result["raw_response"] = raw[:200]
        return result


def _extract_label_from_text(text: str) -> str:
    upper_text = text.upper()
    for candidate_upper, candidate in _LABEL_LOOKUP.items():
        if candidate_upper in upper_text:
            return candidate
    if _PERSON_VARIANT_RE.search(upper_text):
        return "PERSON_k"
    return "UNKNOWN"


def _draw_bbox_on_frame(src: Path, dst: Path, bbox: dict[str, Any]) -> None:
    """Copy src to dst and draw normalized bbox in red."""
    try:
        from PIL import Image, ImageDraw
        with Image.open(src).convert("RGB") as img:
            w, h = img.size
            draw = ImageDraw.Draw(img)
            x1 = int(bbox.get("x_min", 0) * w)
            y1 = int(bbox.get("y_min", 0) * h)
            x2 = int(bbox.get("x_max", 1) * w)
            y2 = int(bbox.get("y_max", 1) * h)
            lw = max(3, round(min(w, h) * 0.006))
            for off in range(lw):
                draw.rectangle((x1 - off, y1 - off, x2 + off, y2 + off), outline=(255, 50, 50))
            img.save(dst, quality=92)
    except Exception:
        shutil.copy2(src, dst)


