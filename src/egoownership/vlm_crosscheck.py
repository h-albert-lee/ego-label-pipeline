def _resolve_frame_paths(
    record: dict[str, Any],
    frames_root: Path | None,
    *,
    videos_root: Path | None = None,
    reconstruction_cache: Path | None = None,
) -> list[Path]:
    """Return [t-2, t-1, t] paths, resolving against frames_root or CWD.

    Falls back to reconstructing frames from a local raw video (via
    ``videos_root``) when the pre-extracted sparse-frame JPEGs aren't present
    — the case for a metadata-only dataset (e.g. downloaded from HuggingFace
    without frame images, for a licensed source dataset like Ego4D whose terms
    don't permit redistributing derived frame crops). See
    ``_reconstruct_frame_paths`` for the reconstruction formula.
    """
    keys = ["frame_t_minus_2_path", "frame_t_minus_1_path", "frame_t_path"]
    paths = []
    for k in keys:
        raw = record.get(k) or ""
        if not raw:
            paths.append(None)
            continue
        p = Path(raw)
        candidates = []
        if frames_root:
            candidates.append(frames_root / p)
        candidates.append(p)                          # relative to CWD
        candidates.append(Path.cwd() / p)            # explicit CWD join
        found = next((c for c in candidates if c.exists()), None)
        paths.append(found)

    if videos_root is not None and any(p is None for p in paths):
        reconstructed = _reconstruct_frame_paths(record, videos_root, reconstruction_cache)
        paths = [existing or reconstructed[i] for i, existing in enumerate(paths)]
    return paths


def _ffmpeg_extract_frame(
    video_path: Path, dest: Path, timestamp_sec: float, *, force: bool = False
) -> Path | None:
    if dest.exists() and not force:
        return dest
    dest.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg", "-hide_banner", "-loglevel", "error",
        "-ss", f"{max(0.0, timestamp_sec):.3f}",
        "-i", str(video_path),
        "-frames:v", "1", "-q:v", "2", "-y", str(dest),
    ]
    try:
        subprocess.run(cmd, check=True)
    except Exception:
        return None
    return dest if dest.exists() else None


def _reconstruct_frame_paths(
    record: dict[str, Any], videos_root: Path, cache_dir: Path | None
) -> list[Path | None]:
    """Reconstruct [t-2, t-1, t] frame images from a local raw video, for a
    metadata-only labels.jsonl (no pre-extracted sparse frames shipped) —
    e.g. an Ego4D-derived dataset, whose license permits sharing our own
    annotations but not redistributing frame crops from the licensed video.

    Needs ``video_id`` (matching Ego4D's own video UID — the raw video is
    expected at ``videos_root/{video_id}.mp4``), ``source_video_start_sec``
    (this clip's offset into that raw video), and ``frame_times_sec`` (local
    offsets within the clip) — all already present in labels.jsonl. The
    absolute timestamp for each tag is simply
    ``source_video_start_sec + frame_times_sec[tag]``.
    """
    video_id = record.get("video_id")
    start = record.get("source_video_start_sec")
    frame_times = record.get("frame_times_sec") or {}
    if not video_id or start is None or not frame_times:
        return [None, None, None]

    video_path = videos_root / f"{video_id}.mp4"
    if not video_path.exists():
        return [None, None, None]

    cache = cache_dir or (videos_root / ".reconstructed_frames")
    cache.mkdir(parents=True, exist_ok=True)
    safe_id = str(record.get("id") or "").replace("/", "_").replace("#", "__")

    results: list[Path | None] = []
    for tag in ("t-2", "t-1", "t"):
        local_sec = frame_times.get(tag)
        if local_sec is None:
            results.append(None)
            continue
        absolute_sec = float(start) + float(local_sec)
        dest = cache / f"{safe_id}__{tag.replace('-', '_')}.jpg"
        results.append(_ffmpeg_extract_frame(video_path, dest, absolute_sec, force=False))
    return results


def _load_existing_ids(path: Path) -> set[str]:
    if not path.exists():
        return set()
    ids: set[str] = set()
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    ids.add(json.loads(line)["id"])
                except (json.JSONDecodeError, KeyError):
                    pass
    return ids


def _load_disagreed_rows(path: Path) -> dict[str, dict[str, Any]]:
    """Full prior-crosscheck rows (keyed by id) where the prior judge(s)
    already disagreed with the auto label (``majority_agrees`` is False).

    Used to skip spending a new judge call on these — a disagreement already
    flags the record for human review, so a second judge's opinion doesn't
    change the triage outcome. The full row (not just the id) is kept so it
    can be passed through unchanged into the new output file, keeping the
    output's row count equal to the input's rather than silently dropping
    these records.
    """
    rows: dict[str, dict[str, Any]] = {}
    if not path.exists():
        return rows
    for row in _iter_jsonl(path):
        if row.get("majority_agrees") is False and row.get("id"):
            rows[row["id"]] = row
    return rows


def write_crosscheck_jsonl(
    labels_path: Path,
    out_path: Path,
    judges: list[Any],
    *,
    frames_root: Path | None = None,
    videos_root: Path | None = None,
    only_agreed_in: Path | None = None,
    limit: int | None = None,
    resume: bool = True,
    show_progress: bool = True,
) -> int:
    """Run all judges on each record in labels_path and write agreement stats.

    ``videos_root``, when given, reconstructs a record's sparse frames from a
    local raw video (videos_root/{video_id}.mp4) whenever the pre-extracted
    JPEGs referenced by frames_root aren't found — for a metadata-only
    labels.jsonl (e.g. downloaded from a HuggingFace dataset that ships our
    own annotations but not frame crops derived from a licensed source video
    like Ego4D). See ``_reconstruct_frame_paths``.

    ``only_agreed_in``, when given, points at an existing crosscheck JSONL
    (e.g. from a prior judge). Records already known to disagree there
    (``majority_agrees: false``) are passed through into the output
    unchanged instead of being re-judged here — a disagreement already
    flags the record for human review, so a second judge's opinion doesn't
    change the triage outcome, only costs more API calls. The output still
    gets one row per input record (same total count as an unfiltered run);
    disagreed rows just carry the prior judge's data forward rather than
    being silently dropped.

    Output schema per row:
      id, auto_ground_truth,
      judges: {model_id: {label, object_type_evidence, zone_evidence,
                           relation_graph_evidence, context_change_evidence, agrees}},
      agreement_count, agreement_ratio, majority_label
    """
    out_path.parent.mkdir(parents=True, exist_ok=True)
    existing_ids = _load_existing_ids(out_path) if resume else set()
    disagreed_rows = _load_disagreed_rows(only_agreed_in) if only_agreed_in else {}

    records = list(_iter_jsonl(labels_path))
    if limit:
        records = records[:limit]

    todo = [r for r in records if r.get("id") not in existing_ids]

    if show_progress:
        try:
            from tqdm.auto import tqdm
            todo = tqdm(todo, total=len(todo), unit="record", desc="vlm-crosscheck")
        except ImportError:
            pass

    n_written = 0
    mode = "a" if resume else "w"
    with out_path.open(mode, encoding="utf-8") as fh:
        for record in todo:
            rid = record.get("id", "")

            if rid in disagreed_rows:
                # Already known to disagree with a prior judge — carry that
                # row forward unchanged rather than spending a new judge
                # call on it, while still keeping the output complete.
                fh.write(json.dumps(disagreed_rows[rid], ensure_ascii=False) + "\n")
                fh.flush()
                n_written += 1
                continue

            auto_gt = record.get("auto_ground_truth") or record.get("auto_label") or ""
            ref_bbox = (record.get("object") or {}).get("bbox") or {}
            temporal_objects = record.get("temporal_target_objects") or {}

            # Frame t always gets ref_bbox (the verified anchor). t-1/t-2 get
            # their own genuinely-tracked box (from --sam2-track) when one
            # exists for that frame; otherwise they're shown unboxed rather
            # than falling back to reusing t's box, which used to draw a
            # stale, unrelated-looking box whenever no real tracked position
            # existed for that frame — which was most of the time.
            raw_paths = _resolve_frame_paths(
                record, frames_root,
                videos_root=videos_root,
                reconstruction_cache=out_path.parent / f"{out_path.stem}_reconstructed_frames",
            )
            with tempfile.TemporaryDirectory() as tmp:
                tmp_path = Path(tmp)
                annotated_paths: list[Path | None] = []
                for tag, src in zip(("t-2", "t-1", "t"), raw_paths):
                    frame_bbox = ref_bbox if tag == "t" else (temporal_objects.get(tag) or {}).get("bbox")
                    if src and src.exists() and frame_bbox:
                        dst = tmp_path / f"frame_{tag.replace('-', '_')}_bbox.jpg"
                        _draw_bbox_on_frame(src, dst, frame_bbox)
                        annotated_paths.append(dst)
                    else:
                        annotated_paths.append(src)  # no genuine box for this frame: shown unboxed

                frame_paths = [p for p in annotated_paths if p and Path(p).exists()]

                judge_results: dict[str, dict] = {}
                for judge in judges:
                    try:
                        result = judge.judge(frame_paths, record)
                    except Exception as exc:
                        result = {"label": "ERROR", **{f: "" for f in _EVIDENCE_FIELDS}, "error": str(exc)[:200]}
                    result["agrees"] = (result.get("label") == auto_gt)
                    judge_results[judge.model_id] = result

            labels_predicted = [v["label"] for v in judge_results.values() if v["label"] in VALID_LABELS]
            agreement_count = sum(1 for v in judge_results.values() if v.get("agrees"))
            majority_label = Counter(labels_predicted).most_common(1)[0][0] if labels_predicted else "UNKNOWN"

            row = {
                "id": rid,
                "auto_ground_truth": auto_gt,
                "judges": judge_results,
                "agreement_count": agreement_count,
                "agreement_ratio": round(agreement_count / max(1, len(judge_results)), 4),
                "majority_label": majority_label,
                "majority_agrees": majority_label == auto_gt,
            }
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
            fh.flush()
            n_written += 1

    return n_written


def merge_crosscheck_jsonl(paths: list[Path], out_path: Path) -> int:
    """Merge two or more crosscheck JSONL files (e.g. separate per-judge runs
    from ``--only-agreed-in``) into one file with every judge's result per id.

    Rows are combined by ``id``; each input's ``judges`` dict is unioned
    together (a later path's judge overwrites an earlier one only if they
    share the same model_id key), and agreement_count/ratio/majority_label/
    majority_agrees are recomputed over the combined judge set. A row missing
    from some inputs but present in others is still included, using
    whichever ones have it.
    """
    rows_by_id: dict[str, dict[str, Any]] = {}
    order: list[str] = []
    for path in paths:
        for row in _iter_jsonl(path):
            rid = row.get("id")
            if not rid:
                continue
            if rid not in rows_by_id:
                order.append(rid)
                rows_by_id[rid] = {"id": rid, "auto_ground_truth": row.get("auto_ground_truth", ""), "judges": {}}
            rows_by_id[rid]["judges"].update(row.get("judges") or {})
            if not rows_by_id[rid]["auto_ground_truth"]:
                rows_by_id[rid]["auto_ground_truth"] = row.get("auto_ground_truth", "")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    n_written = 0
    with out_path.open("w", encoding="utf-8") as fh:
        for rid in order:
            merged = rows_by_id[rid]
            judges = merged["judges"]
            auto_gt = merged["auto_ground_truth"]
            labels_predicted = [v["label"] for v in judges.values() if v.get("label") in VALID_LABELS]
            agreement_count = sum(1 for v in judges.values() if v.get("agrees"))
            majority_label = Counter(labels_predicted).most_common(1)[0][0] if labels_predicted else "UNKNOWN"
            row = {
                "id": rid,
                "auto_ground_truth": auto_gt,
                "judges": judges,
                "agreement_count": agreement_count,
                "agreement_ratio": round(agreement_count / max(1, len(judges)), 4),
                "majority_label": majority_label,
                "majority_agrees": majority_label == auto_gt,
            }
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
            n_written += 1
    return n_written
