@dataclass
class AnthropicOwnershipJudgeConfig:
    model_id: str = "claude-sonnet-4-6"
    max_tokens: int = 512
    api_key: str | None = None  # falls back to ANTHROPIC_API_KEY env var
    # "frames-only" (independent audit) or "with-narration" (adjudication stage
    # that additionally sees the narration + verb). Never aggregate the two.
    evidence_mode: str = "frames-only"


class AnthropicOwnershipJudge:
    def __init__(self, cfg: AnthropicOwnershipJudgeConfig | None = None):
        self.cfg = cfg or AnthropicOwnershipJudgeConfig()
        self.model_id = self.cfg.model_id
        self.evidence_mode = self.cfg.evidence_mode
        self._client: Any = None

    def _load(self) -> Any:
        if self._client is None:
            import os

            import anthropic
            kwargs: dict[str, Any] = (
                {"api_key": self.cfg.api_key} if self.cfg.api_key else {}
            )
            ua = os.environ.get("EGOOWN_ANTHROPIC_USER_AGENT")
            if ua:
                kwargs["default_headers"] = {"User-Agent": ua}
            self._client = anthropic.Anthropic(**kwargs)
        return self._client

    def judge(self, frame_paths: list[Path], record: dict[str, Any]) -> dict[str, Any]:
        import base64
        client = self._load()

        content: list[dict] = []
        for fp in frame_paths:
            if fp.exists():
                data = base64.standard_b64encode(fp.read_bytes()).decode()
                content.append({
                    "type": "image",
                    "source": {"type": "base64", "media_type": "image/jpeg", "data": data},
                })
        prompt = _build_prompt(record, with_narration=self.evidence_mode == "with-narration")
        content.append({"type": "text", "text": prompt})

        response = client.messages.create(
            model=self.cfg.model_id,
            max_tokens=self.cfg.max_tokens,
            system=_SYSTEM,
            messages=[{"role": "user", "content": content}],
        )
        raw = response.content[0].text
        return _parse_label_response(raw)


