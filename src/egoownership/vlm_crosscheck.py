@dataclass
class OpenAIOwnershipJudgeConfig:
    model_id: str = "gpt-4o"
    max_tokens: int = 512
    api_key: str | None = None


class OpenAIOwnershipJudge:
    def __init__(self, cfg: OpenAIOwnershipJudgeConfig | None = None):
        self.cfg = cfg or OpenAIOwnershipJudgeConfig()
        self.model_id = self.cfg.model_id
        self._client: Any = None

    def _load(self) -> Any:
        if self._client is None:
            from openai import OpenAI
            self._client = OpenAI(
                **({"api_key": self.cfg.api_key} if self.cfg.api_key else {})
            )
        return self._client

    def judge(self, frame_paths: list[Path], record: dict[str, Any]) -> dict[str, Any]:
        import base64
        client = self._load()

        content: list[dict] = []
        for fp in frame_paths:
            if fp.exists():
                data = base64.standard_b64encode(fp.read_bytes()).decode()
                content.append({
                    "type": "image_url",
                    "image_url": {"url": f"data:image/jpeg;base64,{data}", "detail": "high"},
                })
        content.append({"type": "text", "text": _build_prompt(record)})

        # gpt-5 / o-series reasoning models reject `max_tokens` and consume
        # part of the budget on hidden reasoning tokens, so use
        # `max_completion_tokens` with extra headroom for them.
        mid = self.cfg.model_id.lower()
        is_reasoning = mid.startswith(("gpt-5", "o1", "o3", "o4"))
        token_kw = (
            {"max_completion_tokens": max(self.cfg.max_tokens, 2048)}
            if is_reasoning
            else {"max_tokens": self.cfg.max_tokens}
        )
        response = client.chat.completions.create(
            model=self.cfg.model_id,
            messages=[
                {"role": "system", "content": _SYSTEM},
                {"role": "user", "content": content},
            ],
            **token_kw,
        )
        raw = response.choices[0].message.content or ""
        return _parse_label_response(raw)


