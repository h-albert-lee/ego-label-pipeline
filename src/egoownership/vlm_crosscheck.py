"""VLM cross-check for labels.jsonl ownership judgements.

Multiple VLM judges independently predict the ownership label (MINE / PERSON_k /
SHARED / AMBIGUOUS) from the 3 sparse frames alone (frame t always gets the
verified reference bbox; t-1/t-2 get their own genuinely-tracked box when
--sam2-track produced one, otherwise shown unboxed rather than reusing a
stale or unrelated fallback box) — no narration, no object visual
description (that's generated by our own captioning stage and would leak the
pipeline's own reasoning), and no access to the pipeline's own zone/relation/
object-type/temporal evidence, so the judge's reasoning is genuinely
independent. Each judge answers with a
label plus one sentence per remaining evidence aspect (object_type_evidence,
zone_evidence, relation_graph_evidence, context_change_evidence) — the same
field names used in scene_records.jsonl's auto_key_evidence, so a judge's
reasoning and the pipeline's own can be compared side-by-side per aspect.
Each judge's answer is compared to ``auto_ground_truth`` and recorded.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

def _iter_jsonl(path: Path) -> Any:
    with path.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    yield json.loads(line)
                except json.JSONDecodeError:
                    pass

VALID_LABELS = {"MINE", "PERSON_k", "SHARED", "AMBIGUOUS"}
# PERSON_k is the only mixed-case label — comparing it after `.upper()`ing an
# extracted candidate (or searching within an upper-cased text blob) silently
# never matches it, since the "k" only appears lowercase. Canonicalize through
# this upper-keyed lookup instead of case-folding VALID_LABELS members directly.
_LABEL_LOOKUP = {label.upper(): label for label in VALID_LABELS}

# "_k" in PERSON_k is a template placeholder — our schema never tracks *which*
# person, just "not the wearer" — but models reasonably read it as "fill in
# the index" and answer PERSON_1 / PERSON_2 / etc. instead of the literal
# string. Treat any such indexed variant as PERSON_k.
_PERSON_VARIANT_RE = re.compile(r"\bPERSON[_ ]?\d+\b")


def _canonicalize_label(raw_label: str) -> str | None:
    candidate = raw_label.strip().upper()
    exact = _LABEL_LOOKUP.get(candidate)
    if exact is not None:
        return exact
    if _PERSON_VARIANT_RE.fullmatch(candidate):
        return "PERSON_k"
    return None

# ---------------------------------------------------------------------------
# Prompt helpers
# ---------------------------------------------------------------------------

_SYSTEM = (
    "You are an expert annotator for egocentric video understanding. "
    "You decide who OWNS or primarily uses a highlighted target object "
    "visible in first-person (ego-camera) footage."
)

_LABEL_DEFS = """\
Label definitions:
  MINE      – the camera wearer (ego) primarily owns / uses this object
  PERSON_k  – another person in the scene primarily owns / uses this object
  SHARED    – ownership is genuinely shared between multiple people
  AMBIGUOUS – impossible to determine from the available evidence
"""


_EVIDENCE_ASPECTS = """\
Reason through these aspects (skip any that aren't determinable from the
frames — don't guess), and answer each in one concise sentence:
  1. Object type          – is this an inherently shared/communal item (e.g. serving-ware,
     condiments) regardless of who's touching it, or a personal-use item (e.g. phone, wallet)?
  2. Zone                 – where it sits relative to the camera wearer vs. other visible people
     (in the wearer's own space, in someone else's space, or on shared/neutral ground)
  3. Relation              – whose hand (if anyone's) is touching or holding it right now
  4. Temporal context      – does its position or holder change across t-2 → t-1 → t?
"""

_EVIDENCE_FIELDS = (
    "object_type_evidence",
    "zone_evidence",
    "relation_graph_evidence",
    "context_change_evidence",
)


def _build_prompt(record: dict[str, Any]) -> str:
    noun = str((record.get("object") or {}).get("label") or record.get("nouns", ["object"])[0])

    lines = [
        f"Target object: {noun}",
        "",
        _LABEL_DEFS,
        "You are shown three frames from the video. The target object is boxed in red",
        "wherever its position is reliably known — always in frame t; in t-2/t-1 too",
        "when available, otherwise those are shown without a box (don't assume the",
        "object is absent just because it isn't boxed there):",
        "  • frame t-2  (2 seconds before the action)",
        "  • frame t-1  (1 second before the action)",
        "  • frame t    (the action moment — always boxed)",
        "",
        _EVIDENCE_ASPECTS,
        "Respond ONLY with valid JSON (no markdown fences), one sentence per field. "
        "If an aspect isn't determinable from the frames, omit that field entirely — "
        "do not guess or fill it with a placeholder:",
        '{"label": "<MINE|PERSON_k|SHARED|AMBIGUOUS>", '
        '"object_type_evidence": "<aspect 1, or omit>", '
        '"zone_evidence": "<aspect 2, or omit>", '
        '"relation_graph_evidence": "<aspect 3, or omit>", '
        '"context_change_evidence": "<aspect 4, or omit>"}',
    ]
    return "\n".join(l for l in lines if l is not None)


